import type { ChatMessage } from "@/lib/ai";
import type { Topic } from "@/lib/knowledge";
import type { DocExcerpt } from "@/lib/fetchDoc";

/**
 * 把「主题 + 抓取到的教程/文档原文」组装成给模型的提示词。
 *
 * 关键定位：AI 不凭空生成知识，而是基于下方“真实原文摘录”（优先是带实战场景的
 * 教程，其次是官方文档）做导读、串讲与学习引导。原文里没有的内容，模型必须
 * 说明是补充/推断，不能编造。
 */
export function buildLessonMessages(
  topic: Topic,
  docs: DocExcerpt[]
): ChatMessage[] {
  const okDocs = docs.filter((d) => d.ok && d.text);

  const docBlocks = okDocs
    .map(
      (d, i) =>
        `【原文 ${i + 1}】来源：${d.label}（${d.url}）\n"""\n${d.text}\n"""`
    )
    .join("\n\n");

  const failed = docs.filter((d) => !d.ok);
  const failedNote =
    failed.length > 0
      ? `\n（注意：以下文档抓取失败，无法引用其原文：${failed
          .map((f) => `${f.label}[${f.error ?? "未知错误"}]`)
          .join("；")}）`
      : "";

  const system = `你是一位资深技术导师，负责“教程/文档导读”。
你的输出必须满足：
1. 全程简体中文，使用 Markdown 格式。
2. 你的讲解必须【基于下方提供的原文摘录】（多为带实战场景的教程，也可能含官方文档）。这是你的一手依据。
3. 严禁编造原文中没有的 API、参数或结论；当你补充原文之外的常识时，用“【补充】”标明。
4. 当原文摘录不足以覆盖某个小节时，如实说明“原文未详述”，不要硬凑。
5. 涉及代码时给出可运行的代码块并标注语言；优先引用/整理原文中的示例。
6. 直接输出正文，不要“好的”“以下是”这类开场白。`;

  const user = `请基于下面抓取到的教程/文档原文，为这个知识点写一篇“导读 + 学习引导”。

【方向】${topic.track}
【技术】${topic.category}
【主题】${topic.title}
【难度】${topic.difficulty}
【本篇目标】${topic.focus}

====== 原文摘录（你的唯一事实依据）======
${docBlocks || "（本次没有成功抓取到任何原文，请明确告知用户，并只给出学习路径与需要阅读的教程/文档，不要编造具体细节。）"}
====== 原文摘录结束 ======${failedNote}

请严格按照下面的 Markdown 结构输出（保留这些二级标题）：

## 一、原文讲了什么（导读）
用通俗的话概括上面原文的核心内容，指出它属于该技术的哪一部分、解决什么问题。必须忠于原文。

## 二、关键概念逐条拆解
从原文里挑出关键概念，逐条“翻译成人话”。每条注明它在原文中对应的说法。原文没提到但重要的，用【补充】标注。

## 三、原文示例解读
整理并解释原文中的代码/示例（若原文无示例，则说明“原文未提供示例”，可给出一个最小【补充】示例并注明）。

## 四、容易误解的点
结合原文，指出 3-5 个初学者容易读错或忽略的地方。

## 五、学习路径（重点）
给出 5-7 步循序渐进、可执行的步骤：每一步说明「读原文的哪一部分 / 动手做什么 / 如何验证掌握」。这是本篇最重要的部分。

## 六、自测清单
给出 5 道左右能检验掌握程度的问题（不用给答案）。

## 七、去哪继续读
基于本篇引用的官方文档链接，说明每个链接适合在什么阶段深入阅读。`;

  return [
    { role: "system", content: system },
    { role: "user", content: user },
  ];
}
